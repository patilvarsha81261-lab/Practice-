# Python Data Types

name = "Samarth"       # String
age = 21               # Integer
height = 5.8           # Float
is_student = True      # Boolean

print("Name:", name)
print("Type:", type(name))

print("Age:", age)
print("Type:", type(age))

print("Height:", height)
print("Type:", type(height))

print("Student:", is_student)
print("Type:", type(is_student))
